#!/usr/bin/env node
// gen-migrations.mjs — generate lib/migrations.ts from db/migrations/*.sql.
//
// Why a generated module instead of reading the directory at runtime: the hosted DATABASE_URL is
// marked Sensitive on Vercel, so it exists ONLY inside a deployed function. The atomic migration
// runner therefore has to run there too (see app/api/migrate/route.ts) — and a serverless bundle
// does not include files nobody imported. Compiling the migrations into a module makes them part
// of the bundle by construction, with no output-file-tracing configuration to get wrong.
//
// tests/unit/migrations-drift.test.ts fails CI if this file is stale, so the generated copy can
// never silently disagree with the .sql files that CI's migration-hygiene check reads.
//
//   node scripts/gen-migrations.mjs           # write lib/migrations.ts
//   node scripts/gen-migrations.mjs --check   # exit 1 if it would change (used by the test)

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join(process.cwd(), 'db', 'migrations');
const OUT = join(process.cwd(), 'lib', 'migrations.ts');

const files = existsSync(DIR)
  ? readdirSync(DIR).filter(f => f.endsWith('.sql')).sort()
  : [];

const entries = files.map(f => {
  const m = f.match(/^(\d+)_/);
  if (!m) {
    process.stderr.write(`✗ ${f} has no numeric version prefix\n`);
    process.exit(2);
  }
  return { version: m[1], name: f, sql: readFileSync(join(DIR, f), 'utf8') };
});

// Backtick template literals keep the SQL readable in review; escape what would break out of one.
const lit = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

const body = `// GENERATED by scripts/gen-migrations.mjs — DO NOT EDIT BY HAND.
// Regenerate with: npm run gen:migrations
//
// db/migrations/*.sql compiled into the bundle so the deployed atomic migration runner
// (POST /api/migrate) can apply them where DATABASE_URL actually exists. Kept honest by
// tests/unit/migrations-drift.test.ts.

export type Migration = { version: string; name: string; sql: string };

export const MIGRATIONS: Migration[] = [
${entries.map(e => `  {
    version: ${JSON.stringify(e.version)},
    name: ${JSON.stringify(e.name)},
    sql: ${lit(e.sql)},
  },`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    process.stderr.write('lib/migrations.ts is STALE — run: npm run gen:migrations\n');
    process.exit(1);
  }
  process.stdout.write(`lib/migrations.ts is current (${entries.length} migration(s))\n`);
  process.exit(0);
}

writeFileSync(OUT, body);
process.stdout.write(`wrote lib/migrations.ts (${entries.length} migration(s): ${entries.map(e => e.version).join(', ')})\n`);
